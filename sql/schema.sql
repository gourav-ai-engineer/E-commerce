-- Olist analytics warehouse schema.
-- Raw CSVs are loaded into raw.* by src/ingestion/load_data.py.
CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS dim_date (
    date_key       INTEGER PRIMARY KEY,
    full_date      DATE NOT NULL UNIQUE,
    year           SMALLINT NOT NULL,
    quarter        SMALLINT NOT NULL,
    month          SMALLINT NOT NULL,
    month_name     VARCHAR(12) NOT NULL,
    year_month     CHAR(7) NOT NULL,
    day_of_month   SMALLINT NOT NULL,
    day_of_week    SMALLINT NOT NULL,
    day_name       VARCHAR(12) NOT NULL,
    is_weekend     BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id        TEXT NOT NULL UNIQUE,
    customer_unique_id TEXT,
    zip_code_prefix    TEXT,
    city               TEXT,
    state              CHAR(2)
);

CREATE TABLE IF NOT EXISTS dim_product (
    product_key               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                TEXT NOT NULL UNIQUE,
    category_name             TEXT,
    category_name_english     TEXT,
    name_length               INTEGER,
    description_length        INTEGER,
    photos_qty                INTEGER,
    weight_g                  NUMERIC,
    length_cm                 NUMERIC,
    height_cm                 NUMERIC,
    width_cm                  NUMERIC
);

CREATE TABLE IF NOT EXISTS dim_seller (
    seller_key       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        TEXT NOT NULL UNIQUE,
    zip_code_prefix  TEXT,
    city             TEXT,
    state            CHAR(2)
);

CREATE TABLE IF NOT EXISTS fact_orders (
    order_id                 TEXT PRIMARY KEY,
    customer_key             BIGINT REFERENCES dim_customer(customer_key),
    order_date_key           INTEGER REFERENCES dim_date(date_key),
    order_status             TEXT NOT NULL,
    purchase_timestamp      TIMESTAMP,
    approved_timestamp      TIMESTAMP,
    delivered_carrier_date  TIMESTAMP,
    delivered_customer_date TIMESTAMP,
    estimated_delivery_date TIMESTAMP,
    item_revenue             NUMERIC(14,2) NOT NULL DEFAULT 0,
    freight_value            NUMERIC(14,2) NOT NULL DEFAULT 0,
    payment_value            NUMERIC(14,2) NOT NULL DEFAULT 0,
    item_count               INTEGER NOT NULL DEFAULT 0,
    review_score             NUMERIC(3,1)
);

CREATE TABLE IF NOT EXISTS fact_order_items (
    order_id             TEXT NOT NULL REFERENCES fact_orders(order_id),
    order_item_id        INTEGER NOT NULL,
    product_key          BIGINT REFERENCES dim_product(product_key),
    seller_key           BIGINT REFERENCES dim_seller(seller_key),
    shipping_limit_date  TIMESTAMP,
    price                NUMERIC(14,2) NOT NULL DEFAULT 0,
    freight_value        NUMERIC(14,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (order_id, order_item_id)
);

CREATE INDEX IF NOT EXISTS idx_fact_orders_purchase_ts ON fact_orders(purchase_timestamp);
CREATE INDEX IF NOT EXISTS idx_fact_orders_customer ON fact_orders(customer_key);
CREATE INDEX IF NOT EXISTS idx_fact_items_product ON fact_order_items(product_key);
CREATE INDEX IF NOT EXISTS idx_fact_items_seller ON fact_order_items(seller_key);
